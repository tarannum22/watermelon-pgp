#!/usr/bin/env bash
# Print the Homebrew formula for a release, from its SHA256SUMS file.
#
#   packaging/homebrew/formula.sh 0.1.0 SHA256SUMS > Formula/watermelon-pgp.rb
#
# Used by the release workflow to update the tap (github.com/tarannum22/homebrew-tap).
set -euo pipefail

version=$1
sums=$2
repo=${GITHUB_REPOSITORY:-tarannum22/watermelon-pgp}

sha() {
  local file="watermelon-pgp-v${version}-$1.tar.gz"
  awk -v f="$file" '$2 == f || $2 == "*"f { print $1 }' "$sums" | grep . \
    || { echo "no checksum for $file in $sums" >&2; exit 1; }
}

url() {
  echo "https://github.com/${repo}/releases/download/v${version}/watermelon-pgp-v${version}-$1.tar.gz"
}

# Look everything up before printing: a failure inside the heredoc below would not stop the script.
sha_mac_arm=$(sha aarch64-apple-darwin)
sha_mac_intel=$(sha x86_64-apple-darwin)
sha_linux_arm=$(sha aarch64-unknown-linux-gnu)
sha_linux_intel=$(sha x86_64-unknown-linux-gnu)

cat <<RUBY
# Generated by packaging/homebrew/formula.sh in ${repo}; changes here are overwritten.
class WatermelonPgp < Formula
  desc "Self-hosted OpenPGP key management and folder encryption jobs, with a web UI"
  homepage "https://tarannum22.github.io/watermelon-pgp/"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "${sha_mac_arm}"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "${sha_mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-gnu)"
      sha256 "${sha_linux_arm}"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-gnu)"
      sha256 "${sha_linux_intel}"
    end
  end

  def install
    bin.install "watermelonpgp"
    doc.install "README.md", "CHANGELOG.md", "docs"
    pkgshare.install "contrib"
  end

  service do
    run [opt_bin/"watermelonpgp", "serve"]
    environment_variables WATERMELONPGP_DATA_DIR: var/"watermelonpgp"
    keep_alive crashed: true
    log_path var/"log/watermelonpgp.log"
    error_log_path var/"log/watermelonpgp.log"
  end

  def caveats
    <<~EOS
      Create the database, master key and admin password once:
        watermelonpgp --data-dir #{var}/watermelonpgp init

      Then run it in the background (web UI on http://127.0.0.1:8080):
        brew services start watermelon-pgp
      or in the foreground:
        watermelonpgp --data-dir #{var}/watermelonpgp serve

      Back up #{var}/watermelonpgp/master.key separately: without it the
      secret keys in the database cannot be recovered.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/watermelonpgp --version")
    ENV["WATERMELONPGP_DATA_DIR"] = testpath/"data"
    pipe_output("#{bin}/watermelonpgp --passphrase-stdin init", "a long test password\\n", 0)
    assert_path_exists testpath/"data/watermelonpgp.db"
    assert_match "Created customer", shell_output("#{bin}/watermelonpgp customer add ACME")
  end
end
RUBY
